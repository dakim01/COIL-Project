def load_obj(path):
    """Minimal OBJ loader. Returns (triangles, bbox_min, bbox_max) where
    triangles is a flat list of (pos, normal) tuples, fan-triangulated,
    with flat face normals computed for any face lacking vn data."""
    verts = []
    norms = []
    faces = []
    with open(path, "r", errors="replace") as f:
        for line in f:
            line = line.strip()
            if line.startswith("v "):
                parts = line.split()
                verts.append(tuple(float(x) for x in parts[1:4]))
            elif line.startswith("vn "):
                parts = line.split()
                norms.append(tuple(float(x) for x in parts[1:4]))
            elif line.startswith("f "):
                parts = line.split()[1:]
                face = []
                for p in parts:
                    bits = p.split("/")
                    vi = int(bits[0]) - 1 if int(bits[0]) > 0 else len(verts) + int(bits[0])
                    ni = None
                    if len(bits) >= 3 and bits[2]:
                        ni = int(bits[2]) - 1 if int(bits[2]) > 0 else len(norms) + int(bits[2])
                    face.append((vi, ni))
                faces.append(face)

    if not verts:
        raise ValueError("No vertices found in OBJ file")

    xs = [v[0] for v in verts]; ys = [v[1] for v in verts]; zs = [v[2] for v in verts]
    bbox_min = (min(xs), min(ys), min(zs))
    bbox_max = (max(xs), max(ys), max(zs))

    tris = []
    for face in faces:
        for i in range(1, len(face) - 1):
            for idx in (0, i, i + 1):
                vi, ni = face[idx]
                pos = verts[vi]
                nrm = norms[ni] if (ni is not None and ni < len(norms)) else None
                tris.append((pos, nrm))

    def face_normal(p0, p1, p2):
        ux, uy, uz = p1[0]-p0[0], p1[1]-p0[1], p1[2]-p0[2]
        vx, vy, vz = p2[0]-p0[0], p2[1]-p0[1], p2[2]-p0[2]
        nx, ny, nz = uy*vz-uz*vy, uz*vx-ux*vz, ux*vy-uy*vx
        length = math.sqrt(nx*nx+ny*ny+nz*nz) or 1.0
        return (nx/length, ny/length, nz/length)

    fixed = []
    for i in range(0, len(tris), 3):
        tri = tris[i:i+3]
        if len(tri) < 3:
            continue
        if any(t[1] is None for t in tri):
            fn = face_normal(tri[0][0], tri[1][0], tri[2][0])
            tri = [(p, fn) for p, n in tri]
        fixed.extend(tri)

    return fixed, bbox_min, bbox_max


class OrbitViewer(QOpenGLWidget):
    """Drag to orbit, scroll to zoom. No GLU dependency (manual projection
    and view matrices), so it doesn't need libGLU to be present."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.tris = []
        self.center = (0.0, 0.0, 0.0)
        self.radius = 1.0
        self.azimuth = 35.0
        self.elevation = 15.0
        self.distance = 3.0
        self._last_pos = None
        self._error = None

    def load_mesh(self, path):
        self.tris, bmin, bmax = load_obj(path)
        cx = (bmin[0]+bmax[0])/2; cy = (bmin[1]+bmax[1])/2; cz = (bmin[2]+bmax[2])/2
        self.center = (cx, cy, cz)
        dx, dy, dz = bmax[0]-bmin[0], bmax[1]-bmin[1], bmax[2]-bmin[2]
        self.radius = max(dx, dy, dz, 1e-3) / 2.0
        self.distance = self.radius * 4.5
        self.azimuth, self.elevation = 35.0, 15.0
        self.update()
        return len(self.tris) // 3, bmin, bmax

    def initializeGL(self):
        GL.glEnable(GL.GL_DEPTH_TEST)
        GL.glEnable(GL.GL_LIGHTING)
        GL.glEnable(GL.GL_LIGHT0)
        GL.glEnable(GL.GL_NORMALIZE)
        GL.glEnable(GL.GL_COLOR_MATERIAL)
        GL.glLightfv(GL.GL_LIGHT0, GL.GL_POSITION, [1.0, 1.0, 1.0, 0.0])
        GL.glLightfv(GL.GL_LIGHT0, GL.GL_DIFFUSE, [0.85, 0.85, 0.9, 1.0])
        GL.glLightfv(GL.GL_LIGHT0, GL.GL_AMBIENT, [0.25, 0.25, 0.28, 1.0])
        GL.glClearColor(0.04, 0.047, 0.055, 1.0)

    def resizeGL(self, w, h):
        GL.glViewport(0, 0, max(w, 1), max(h, 1))
        GL.glMatrixMode(GL.GL_PROJECTION)
        GL.glLoadIdentity()
        fovy_deg, near, far = 40.0, 0.01, 1e6
        aspect = w / max(h, 1)
        top = near * math.tan(math.radians(fovy_deg) / 2.0)
        right = top * aspect
        GL.glFrustum(-right, right, -top, top, near, far)
        GL.glMatrixMode(GL.GL_MODELVIEW)

    def paintGL(self):
        GL.glClear(GL.GL_COLOR_BUFFER_BIT | GL.GL_DEPTH_BUFFER_BIT)
        GL.glLoadIdentity()
        GL.glTranslatef(0.0, 0.0, -self.distance)
        GL.glRotatef(-self.elevation, 1.0, 0.0, 0.0)
        GL.glRotatef(-self.azimuth, 0.0, 1.0, 0.0)
        GL.glTranslatef(-self.center[0], -self.center[1], -self.center[2])

        if self.tris:
            GL.glColor3f(0.66, 0.70, 0.78)
            GL.glBegin(GL.GL_TRIANGLES)
            for pos, nrm in self.tris:
                GL.glNormal3f(*nrm)
                GL.glVertex3f(*pos)
            GL.glEnd()

    def mousePressEvent(self, e):
        self._last_pos = e.pos()

    def mouseMoveEvent(self, e):
        if self._last_pos is None:
            return
        dx = e.pos().x() - self._last_pos.x()
        dy = e.pos().y() - self._last_pos.y()
        self.azimuth -= dx * 0.4
        self.elevation = max(-89.0, min(89.0, self.elevation + dy * 0.4))
        self._last_pos = e.pos()
        self.update()

    def mouseReleaseEvent(self, e):
        self._last_pos = None

    def wheelEvent(self, e):
        self.distance *= (0.9 if e.angleDelta().y() > 0 else 1.1)
        self.distance = max(self.radius * 0.15, self.distance)
        self.update()


class ParamRow(QWidget):
    def __init__(self, key, label, vmin, vmax, step, decimals, on_change):
        super().__init__()
        self.key = key
        self.decimals = decimals
        self.on_change = on_change
        self.scale = 10 ** decimals

        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 10)

        top = QHBoxLayout()
        self.label = QLabel(label)
        self.spin = QDoubleSpinBox()
        self.spin.setRange(vmin, vmax)
        self.spin.setSingleStep(step)
        self.spin.setDecimals(decimals)
        self.spin.setValue(DEFAULT_PARAMS[key])
        self.spin.setFixedWidth(90)
        top.addWidget(self.label)
        top.addStretch()
        top.addWidget(self.spin)
        layout.addLayout(top)

        self.slider = QSlider(Qt.Horizontal)
        self.slider.setRange(int(vmin * self.scale), int(vmax * self.scale))
        self.slider.setValue(int(DEFAULT_PARAMS[key] * self.scale))
        layout.addWidget(self.slider)

        self.slider.valueChanged.connect(self._from_slider)
        self.spin.valueChanged.connect(self._from_spin)

    def _from_slider(self, v):
        val = v / self.scale
        self.spin.blockSignals(True)
        self.spin.setValue(val)
        self.spin.blockSignals(False)
        self.on_change()

    def _from_spin(self, val):
        self.slider.blockSignals(True)
        self.slider.setValue(int(val * self.scale))
        self.slider.blockSignals(False)
        self.on_change()

    def value(self):
        return self.spin.value()

    def set_value(self, v):
        self.spin.setValue(v)



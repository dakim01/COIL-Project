    # ---------- Render pipeline ----------

    def start_render(self):
        dist = self.dist_edit.text().strip()

        mitsuba_exe = os.path.join(dist, "mitsuba.exe")
        mtsutil_exe = os.path.join(dist, "mtsutil.exe")

        missing = []
        if not os.path.isfile(mitsuba_exe):
            missing.append(f"mitsuba.exe (expected at {mitsuba_exe})")
        if not os.path.isfile(mtsutil_exe):
            missing.append(f"mtsutil.exe (expected at {mtsutil_exe})")

        if self.radio_mesh.isChecked():
            c = self.current_camera()
            mesh_path = os.path.join(dist, c["mesh_file"])
            envmap_path = os.path.join(dist, c["envmap_file"])
            if not os.path.isfile(mesh_path):
                missing.append(f"{c['mesh_file']} (expected at {mesh_path})")
            elif os.path.getsize(mesh_path) < 100:
                missing.append(f"{c['mesh_file']} exists but looks empty/corrupt ({mesh_path})")
            if not os.path.isfile(envmap_path):
                missing.append(f"{c['envmap_file']} (expected at {envmap_path})")

        if missing:
            QMessageBox.critical(
                self, "Missing files",
                "Cannot render -- the following required files were not found:\n\n"
                + "\n".join(f"\u2022 {m}" for m in missing)
                + "\n\nPlace them in the dist folder above and try again."
            )
            return

        scene_path = os.path.join(dist, SCENE_XML)
        try:
            with open(scene_path, "w", encoding="utf-8") as f:
                f.write(self.xml_view.toPlainText())
        except OSError as e:
            QMessageBox.critical(self, "Write failed", f"Could not write {scene_path}:\n{e}")
            return

        self.render_btn.setEnabled(False)
        self.render_btn.setText("Rendering...")
        self.log_view.clear()
        self._append_log(f"Mode: {'Mesh + Environment' if self.radio_mesh.isChecked() else 'Sphere'}")
        self._append_log(f"Writing scene to {scene_path}")
        self._append_log(f"Running mitsuba.exe {SCENE_XML} ...")

        self.stage = "mitsuba"
        self.proc = QProcess(self)
        self.proc.setWorkingDirectory(dist)
        self.proc.readyReadStandardOutput.connect(self._on_proc_output)
        self.proc.readyReadStandardError.connect(self._on_proc_output)
        self.proc.finished.connect(self._on_stage_finished)
        self.proc.errorOccurred.connect(self._on_proc_error)
        self.proc.start(mitsuba_exe, [SCENE_XML])

    def _on_proc_error(self, error):
        self._append_log(f"[process error] {error}")
        self.render_btn.setEnabled(True)
        self.render_btn.setText("Render")

    def _on_proc_output(self):
        if self.proc is None:
            return
        out = bytes(self.proc.readAllStandardOutput()).decode(errors="replace")
        err = bytes(self.proc.readAllStandardError()).decode(errors="replace")
        if out:
            self._append_log(out.rstrip())
        if err:
            self._append_log(err.rstrip())

    def _on_stage_finished(self, exit_code, _status):
        dist = self.dist_edit.text().strip()

        if self.stage == "mitsuba":
            if exit_code != 0:
                self._append_log(f"mitsuba.exe exited with code {exit_code} -- see log above for the error.")
                self.render_btn.setEnabled(True)
                self.render_btn.setText("Render")
                return
            exr_path = os.path.join(dist, SCENE_EXR)
            if not os.path.isfile(exr_path):
                self._append_log(f"mitsuba.exe finished but {SCENE_EXR} was not created.")
                self.render_btn.setEnabled(True)
                self.render_btn.setText("Render")
                return
            self._append_log("Render finished. Tonemapping ...")
            self.stage = "tonemap"
            mtsutil_exe = os.path.join(dist, "mtsutil.exe")
            self.proc = QProcess(self)
            self.proc.setWorkingDirectory(dist)
            self.proc.readyReadStandardOutput.connect(self._on_proc_output)
            self.proc.readyReadStandardError.connect(self._on_proc_output)
            self.proc.finished.connect(self._on_stage_finished)
            self.proc.errorOccurred.connect(self._on_proc_error)
            self.proc.start(mtsutil_exe, ["tonemap", SCENE_EXR])
            return

        if self.stage == "tonemap":
            self.render_btn.setEnabled(True)
            self.render_btn.setText("Render")
            if exit_code != 0:
                self._append_log(f"mtsutil.exe exited with code {exit_code}")
                return
            png_path = os.path.join(dist, SCENE_PNG)
            if not os.path.isfile(png_path):
                self._append_log(f"Expected {SCENE_PNG} but it was not found.")
                return
            self._append_log("Done.")
            self._save_run(png_path)

    def _append_log(self, text):
        self.log_view.appendPlainText(text)

    # ---------- Run history (kept internally; surfaced only in Export tab) ----------

    def _load_log(self):
        if os.path.isfile(LOG_FILE):
            try:
                with open(LOG_FILE, "r", encoding="utf-8") as f:
                    return json.load(f)
            except (OSError, json.JSONDecodeError):
                return []
        return []

    def _save_log(self):
        try:
            with open(LOG_FILE, "w", encoding="utf-8") as f:
                json.dump(self.runs, f, indent=2)
        except OSError as e:
            QMessageBox.warning(self, "Could not save log", str(e))

    def _save_run(self, png_path):
        label = self.label_edit.text().strip() or "run"
        safe_label = "".join(c if c.isalnum() or c in "-_" else "_" for c in label)
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        dest_name = f"{safe_label}_{timestamp}.png"
        dest_path = os.path.join(RUNS_DIR, dest_name)
        try:
            shutil.copyfile(png_path, dest_path)
        except OSError as e:
            self._append_log(f"Could not copy render into history: {e}")
            dest_path = png_path

        run = {
            "label": label,
            "mode": "mesh" if self.radio_mesh.isChecked() else "sphere",
            "params": self.current_params(),
            "camera": self.current_camera() if self.radio_mesh.isChecked() else None,
            "image": dest_path,
            "time": datetime.now().isoformat(timespec="seconds"),
        }
        self.runs.append(run)
        self._save_log()
        self._refresh_export_list()
        self._set_preview(dest_path)

    def _set_preview(self, path):
        pix = QPixmap(path)
        if not pix.isNull():
            self.preview_label.setText("")
            self.preview_label.setPixmap(pix.scaled(
                self.preview_label.width(), self.preview_label.height(),
                Qt.KeepAspectRatio, Qt.SmoothTransformation))

    # ---------- Export tab ----------

    def _refresh_export_list(self):
        self.export_list.clear()
        for run in reversed(self.runs):
            p = run["params"]
            mode = run.get("mode", "sphere")
            text = (f"[{mode}] {run['label']}  \u2014  "
                    f"D={p['height']:.0f} \u03b72={p['filmEta']:.2f} "
                    f"\u03b73={p['eta']:.2f} \u03ba3={p['k']:.2f} \u03b1={p['alpha']:.4f}  "
                    f"\u2014  {run['time']}")
            item = QListWidgetItem(text)
            item.setFlags(item.flags() | Qt.ItemIsUserCheckable)
            item.setCheckState(Qt.Checked)
            if os.path.isfile(run["image"]):
                item.setIcon(QIcon(QPixmap(run["image"]).scaled(
                    64, 64, Qt.KeepAspectRatio, Qt.SmoothTransformation)))
            item.setData(Qt.UserRole, run)
            self.export_list.addItem(item)

    def _set_all_checked(self, checked):
        state = Qt.Checked if checked else Qt.Unchecked
        for i in range(self.export_list.count()):
            self.export_list.item(i).setCheckState(state)

    def _do_export(self):
        selected = []
        for i in range(self.export_list.count()):
            item = self.export_list.item(i)
            if item.checkState() == Qt.Checked:
                run = item.data(Qt.UserRole)
                if run and os.path.isfile(run["image"]):
                    selected.append(run)

        if not selected:
            QMessageBox.information(self, "Nothing to export", "No images selected (or no renders yet).")
            return

        dest = self.export_dest_edit.text().strip()
        try:
            os.makedirs(dest, exist_ok=True)
        except OSError as e:
            QMessageBox.critical(self, "Export failed", f"Could not create destination folder:\n{e}")
            return

        if self.zip_checkbox.isChecked():
            zip_name = f"thinfilm_export_{datetime.now().strftime('%Y%m%d_%H%M%S')}.zip"
            zip_path = os.path.join(dest, zip_name)
            try:
                with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
                    manifest = []
                    for run in selected:
                        arcname = os.path.basename(run["image"])
                        zf.write(run["image"], arcname)
                        manifest.append({
                            "file": arcname, "label": run["label"], "mode": run.get("mode"),
                            "params": run["params"], "time": run["time"],
                        })
                    zf.writestr("manifest.json", json.dumps(manifest, indent=2))
            except OSError as e:
                QMessageBox.critical(self, "Export failed", f"Could not write zip file:\n{e}")
                return
            QMessageBox.information(self, "Export complete", f"Exported {len(selected)} image(s) to:\n{zip_path}")
        else:
            copied = 0
            errors = []
            for run in selected:
                try:
                    shutil.copyfile(run["image"], os.path.join(dest, os.path.basename(run["image"])))
                    copied += 1
                except OSError as e:
                    errors.append(f"{os.path.basename(run['image'])}: {e}")
            msg = f"Exported {copied} of {len(selected)} image(s) to:\n{dest}"
            if errors:
                msg += "\n\nErrors:\n" + "\n".join(errors)
            QMessageBox.information(self, "Export complete", msg)



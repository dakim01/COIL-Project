    # ---------- 3D View actions ----------

    def _reload_3d_mesh(self):
        if not HAS_OPENGL:
            return
        dist = self.dist_edit.text().strip()
        mesh_name = self.mesh_file_edit.text().strip() or DEFAULT_CAMERA["mesh_file"]
        mesh_path = os.path.join(dist, mesh_name)
        if not os.path.isfile(mesh_path):
            QMessageBox.critical(self, "Not found", f"Mesh file not found:\n{mesh_path}")
            return
        try:
            n_tris, bmin, bmax = self.gl_viewer.load_mesh(mesh_path)
        except Exception as e:
            QMessageBox.critical(self, "Load failed", f"Could not load {mesh_name}:\n{e}")
            return
        self.mesh3d_status.setText(
            f"Loaded {n_tris} triangles. Bounds: "
            f"X[{bmin[0]:.1f}, {bmax[0]:.1f}]  Y[{bmin[1]:.1f}, {bmax[1]:.1f}]  "
            f"Z[{bmin[2]:.1f}, {bmax[2]:.1f}]"
        )

    def _sync_camera_from_3d(self):
        if not HAS_OPENGL or not self.gl_viewer.tris:
            QMessageBox.information(self, "No mesh loaded", "Load a mesh in the 3D View tab first.")
            return
        v = self.gl_viewer
        el = math.radians(v.elevation)
        origin_y = v.center[1] + v.distance * math.sin(el)
        origin_z = v.distance * math.cos(el)
        self.target_y_spin.setValue(v.center[1])
        self.origin_y_spin.setValue(origin_y)
        self.origin_z_spin.setValue(origin_z)
        note = ""
        if abs(v.azimuth) > 3:
            note = ("\n\nNote: the 3D view's azimuth "
                     f"({v.azimuth:.0f}\u00b0) can't carry over -- the render "
                     "camera is fixed to a front-on view. Only distance and "
                     "elevation were synced.")
        QMessageBox.information(
            self, "Camera synced",
            f"Render tab camera updated:\ntarget Y = {v.center[1]:.1f}\n"
            f"origin Y = {origin_y:.1f}\norigin Z = {origin_z:.1f}{note}"
        )
        self.refresh_outputs()

